/* data.h: BCC's global data, at its offsets in the data segment (DGROUP).

   In the first stage the data stays where the DOS program kept it, so a global is a far
   pointer into DGROUP plus an accessor of its type.  Each entry gives the DS offset from
   ../bcc20/symbols.tsv and its declaration.  The items of ../bcc20/src/include/DATA.H are
   in globals.h, generated by tools/genglobals.py (NAME, NAME_AT(i), NAME_P); items that
   sources declare for themselves are added here by hand as translated code needs them.  DGROUP is the data
   segment's paragraph: replay sets it from the recorded DS. */
#ifndef DATA_H
#define DATA_H
#include "port.h"

extern u16 DGROUP;
#define DSPTR(off) MK_FP(DGROUP, (off))

/* unsigned char _CTYPE[257]: character classes, indexed by character + 1 (entry 0 is EOF):
   1 space, 2 digit, 4 upper case, 8 lower case, ... (Turbo C's ctype table) */
#define _CTYPE_P DSPTR(0x5B80)
#define CTYPE(c) B(fp_add(_CTYPE_P, (c) + 1))

/* pool descriptors declared as structs in the sources (struct Pool, struct C31Bank): their
   first word is the pool's segment, which is all pool.h needs */
#define SCOPE_POOL_SEG W(DSPTR(0x782A))
#define NAME_POOL_SEG W(DSPTR(0x7832))
#define HASH_CHAIN_LINK_SEG W(DSPTR(0x783A))
#define EXPR_POOL_SEG W(DSPTR(0x8186))
#define SRCFILE_POOL_SEG W(DSPTR(0x818E))
#define FLOW_BLOCK_POOL_SEG W(DSPTR(0x8654))
#define VARIABLE_TABLE_SEG W(DSPTR(0x866E))

#include "globals.h"

#endif
