/* stack.c: BCC.EXE's 8086 stack, modelled for its stack checks (README.md, "Decisions for the
   native build").  Eight recursive functions of the original stop the compile with "Out of
   memory" when SP is below 8F0Ch at their check (`if(_SP<0x8F0C) REPORT_FATAL(...)`), so a
   deeply nested source fails in BCC.EXE.  The native build runs on the host's stack; to
   stop where BCC.EXE does it keeps a virtual SP:

   - every function of src/ is compiled with -finstrument-functions, and the hooks below
     keep a shadow stack of the calls open;
   - a translated function entered from another (its nearest translated caller: the port's
     own helpers count as part of their caller) lowers the virtual SP by the drop BCC.EXE
     showed for that caller and callee (stack_table.c, measured over the corpus with
     tools/record.py --sp and generated by tools/genstack.py); RMAIN13C starts at the SP
     BCC.EXE's start-up code enters it with, which depends on the command line (main);
   - each check (STACK_CHECK, include/stack.h) compares the virtual SP, less the frame the
     function had built before its check in BCC.EXE, with 8F0Ch;
   - a long jump (C45_LONGJUMP) puts the shadow stack back where its C45_SETJUMP left it.

   A caller and callee pair BCC.EXE never showed lowers the SP by the callee's most common
   drop from any caller (or 10h), which only matters if such a pair lies on a deep chain.
   BCC_STACK_LIMIT=0 turns the checks off (the host's stack is then the only limit). */
#include <stdio.h>
#include <stdlib.h>
#include "port.h"
#include "native.h"
#include "stack_table.h"

#define SHADOW_MAX 100000

typedef struct {
    void *fn;           /* the function entered */
    void *known;        /* the nearest translated function, itself or a caller */
    i32 sp;             /* the virtual SP at known's entry (it may go below 0 on a chain no
                           check stops) */
} Shadow;

static Shadow shadow[SHADOW_MAX];
static unsigned depth, overflow;
static int enabled = -1;
static i32 root_sp = 0x9D8C;        /* RMAIN13C's SP at entry: set by main (native.c) */

/* function → index into STACK_FUNCTIONS, by open addressing on the address */
#define HASH_SIZE 8192
static struct { void *fn; int index; } by_fn[HASH_SIZE];
/* (callee, caller) → drop */
#define PAIR_SIZE 32768
static struct { void *callee, *caller; u16 drop; u8 used; } by_pair[PAIR_SIZE];

static unsigned hash_ptr(const void *p) { return (unsigned)(((uintptr_t)p >> 3) * 2654435761u); }

__attribute__((no_instrument_function)) static int function_index(void *fn)
{
    for (unsigned h = hash_ptr(fn) & (HASH_SIZE - 1);; h = (h + 1) & (HASH_SIZE - 1)) {
        if (by_fn[h].fn == fn)
            return by_fn[h].index;
        if (!by_fn[h].fn)
            return -1;
    }
}

static int forced = -1;         /* native_stack_enable */

__attribute__((no_instrument_function)) void native_stack_enable(int on)
{
    forced = on;
    if (enabled >= 0)
        enabled = on >= 0 ? on : enabled;
}

__attribute__((no_instrument_function)) static void setup(void)
{
    const char *e = getenv("BCC_STACK_LIMIT");
    enabled = forced >= 0 ? forced : !(e && e[0] == '0');
    for (int i = 0; i < STACK_FUNCTION_COUNT; i++) {
        unsigned h = hash_ptr(STACK_FUNCTIONS[i].fn) & (HASH_SIZE - 1);
        while (by_fn[h].fn)
            h = (h + 1) & (HASH_SIZE - 1);
        by_fn[h].fn = STACK_FUNCTIONS[i].fn;
        by_fn[h].index = i;
    }
    for (int i = 0; i < STACK_DROP_COUNT; i++) {
        void *callee = STACK_FUNCTIONS[STACK_DROPS[i].callee].fn;
        void *caller = STACK_FUNCTIONS[STACK_DROPS[i].caller].fn;
        unsigned h = (hash_ptr(callee) ^ hash_ptr(caller) * 31) & (PAIR_SIZE - 1);
        while (by_pair[h].used)
            h = (h + 1) & (PAIR_SIZE - 1);
        by_pair[h].callee = callee;
        by_pair[h].caller = caller;
        by_pair[h].drop = STACK_DROPS[i].drop;
        by_pair[h].used = 1;
    }
}

__attribute__((no_instrument_function)) static u16 drop_for(void *callee, int index, void *caller)
{
    for (unsigned h = (hash_ptr(callee) ^ hash_ptr(caller) * 31) & (PAIR_SIZE - 1);
         by_pair[h].used; h = (h + 1) & (PAIR_SIZE - 1))
        if (by_pair[h].callee == callee && by_pair[h].caller == caller)
            return by_pair[h].drop;
    return STACK_FUNCTIONS[index].usual_drop;
}

__attribute__((no_instrument_function)) void __cyg_profile_func_enter(void *fn, void *site)
{
    (void)site;
    if (enabled < 0)
        setup();
    if (depth == SHADOW_MAX) {
        overflow++;
        return;
    }
    Shadow *s = &shadow[depth];
    s->fn = fn;
    int index = function_index(fn);
    const Shadow *up = depth ? &shadow[depth - 1] : 0;
    if (index < 0) {            /* the port's own helper: part of its caller's frame */
        s->known = up ? up->known : 0;
        s->sp = up ? up->sp : root_sp;
    } else {
        s->known = fn;
        s->sp = up && up->known ? up->sp - drop_for(fn, index, up->known) : root_sp;
    }
    depth++;
}

__attribute__((no_instrument_function)) void __cyg_profile_func_exit(void *fn, void *site)
{
    (void)fn;
    (void)site;
    if (overflow)
        overflow--;
    else if (depth)
        depth--;
}

__attribute__((no_instrument_function)) unsigned native_stack_depth(void) { return depth; }

__attribute__((no_instrument_function)) void native_stack_set_root(i32 sp) { root_sp = sp; }

__attribute__((no_instrument_function)) void native_stack_unwind(unsigned to)
{
    overflow = 0;
    if (to < depth)
        depth = to;
}

/* STACK_CHECK: 1 when BCC.EXE's SP would be below limit at fn's check */
__attribute__((no_instrument_function)) int native_stack_below(u16 limit, void *fn)
{
    if (enabled < 0)
        setup();
    if (!enabled || !depth)
        return 0;
    if (overflow)
        return 1;
    const Shadow *s = &shadow[depth - 1];
    int index = function_index(fn);
    if (s->known != fn || index < 0)
        return 0;
    return s->sp - STACK_FUNCTIONS[index].check < (i32)limit;
}
