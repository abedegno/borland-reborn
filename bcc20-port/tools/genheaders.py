"""Write the port's copies of the original's shared definitions, and include/globals.h.

    python3 tools/genheaders.py

From ../bcc20/src/include:
- FIELDS.H, MSG.H, TOKEN.H, KIND.H, EXPROP.H (record field offsets, message numbers, token
  codes, type kinds, expression operators: numbers only) -> include/fields.h, msg.h,
  token.h, kind.h, exprop.h, unchanged but for the include guard;
- POOL.H (field access in the far record pools) -> include/pool.h, each accessor rewritten
  for the port's memory model: NAME(r, o) is the field at offset o of record r of the pool
  whose segment is in the named global.  The ES_x forms are left out: the port has no ES
  register, so a translation names the segment (FAR_x(segment, r, o)).
Then runs tools/genglobals.py.  Every pool segment POOL.H names must be a global.
"""
import re
import subprocess
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
INC = PORT.parent / "bcc20" / "src" / "include"
ACC = {"unsigned int": "W", "int": "SW", "unsigned char": "B", "signed char": "SB",
       "char": "SB", "long": "SD", "unsigned long": "D"}
NOTE = "   (generated by tools/genheaders.py from ../bcc20/src/include/{0}; do not edit) */"


def copy_constants(name):
    text = (INC / f"{name}.H").read_text(encoding="latin1")
    first = text.index("*/")
    text = text[:first].rstrip() + "\n" + NOTE.format(f"{name}.H") + text[first + 2:]
    text = re.sub(rf"\b{name}_H\b", f"PORT_{name}_H", text)
    text = re.sub(r'#include "(\w+)\.H"', lambda m: f'#include "{m.group(1).lower()}.h"', text)
    (PORT / "include" / f"{name.lower()}.h").write_text(text)


def pool():
    out = ["/* pool.h: field access in BCC's far record pools, for the port's memory model.",
           "   NAME(r, o) is the field at offset o (FIELDS.H) of record r, in the pool whose",
           "   segment is in the global the line names; FAR_x(s, r, o) the same in segment s,",
           "   AT_x(s, o) the item at s:o.  Suffixes: W u16, I/SW i16, B u8, SC/SB i8, L i32,",
           "   UL u32.  ES_x of the original (the segment in ES) has no port form: name the",
           NOTE.format("POOL.H").replace("   (", "   segment.  ("),
           "#ifndef PORT_POOL_H", "#define PORT_POOL_H", '#include "data.h"', '#include "fields.h"', ""]
    pools = set()
    for line in (INC / "POOL.H").read_text(encoding="latin1").splitlines():
        m = re.match(r"#define (\w+)\(([^)]*)\)\s+\(\*\(([a-z ]+?) far \*\)MK_FP\((.*)\)\)\s*$", line)
        if not m:
            continue
        name, params, ctype, args = m.groups()
        if name.startswith("ES_"):
            continue
        seg = args.split(",")[0].strip("() ")
        if seg not in ("s",):
            pools.add(seg)
        out.append(f"#define {name}({params}) {ACC[ctype]}(MK_FP({args}))")
    out += ["", "#endif", ""]
    (PORT / "include" / "pool.h").write_text("\n".join(out))
    return pools


def main():
    for name in ("FIELDS", "MSG", "TOKEN", "KIND", "EXPROP"):
        copy_constants(name)
    pools = pool()
    subprocess.run([sys.executable, str(PORT / "tools" / "genglobals.py")], check=True)
    globals_h = (PORT / "include" / "globals.h").read_text() + (PORT / "include" / "data.h").read_text()
    missing = sorted(p for p in pools if f"#define {p} " not in globals_h)
    if missing:
        print(f"genheaders: pool segments that are not globals: {' '.join(missing)}")
    print(f"include/pool.h: {len(pools)} pools")


if __name__ == "__main__":
    main()
