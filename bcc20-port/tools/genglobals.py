"""Write include/globals.h: an accessor for every global of ../bcc20/src/include/DATA.H.

    python3 tools/genglobals.py

DATA.H declares BCC's data one item per line, in address order, with its DS offset.  For
each item this writes, at that offset in DGROUP (include/data.h):

    NAME_P          a far pointer to it
    NAME            the item as an lvalue, for a scalar (near pointers are u16 offsets)
    NAME_AT(i)      element i as an lvalue, for an array

Items declared elsewhere (sources that view the same bytes in different ways) go by hand
in include/data.h.
"""
import re
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
DATA_H = PORT.parent / "bcc20" / "src" / "include" / "DATA.H"

# element type -> (size, accessor macro of port.h)
TYPES = {
    "unsigned int": (2, "W"), "int": (2, "SW"),
    "unsigned char": (1, "B"), "char": (1, "SB"), "signed char": (1, "SB"),
    "unsigned long": (4, "D"), "long": (4, "SD"),
    "char near *": (2, "W"), "unsigned char near *": (2, "W"),
}
LINE = re.compile(r"^extern\s+(.+?)\s*\b([A-Za-z_]\w*)\s*(\[[^\]]*\])?\s*;\s*/\*\s*DS:([0-9A-F]{4})\b")


def main():
    out = ["/* globals.h: BCC's global data, generated by tools/genglobals.py from",
           "   ../bcc20/src/include/DATA.H.  Do not edit; see include/data.h. */",
           "#ifndef GLOBALS_H", "#define GLOBALS_H", '#include "data.h"', ""]
    count = 0
    for line in DATA_H.read_text(encoding="latin1").splitlines():
        m = LINE.match(line)
        if not m:
            continue
        ctype, name, array, off = m.groups()
        ctype = re.sub(r"\s+", " ", ctype.replace("near", " near ").strip())
        ctype = ctype.replace(" near *", " near *").replace("near *", "near *")
        key = re.sub(r"\s+near$", "", ctype)          # `char near X[]`: the array is near data
        if key not in TYPES:
            raise SystemExit(f"genglobals: no port type for `{ctype}` ({name})")
        size, acc = TYPES[key]
        out.append(f"#define {name}_P DSPTR(0x{off})")
        if array is not None:
            index = "(i)" if size == 1 else f"(i) * {size}"
            out.append(f"#define {name}_AT(i) {acc}(fp_add({name}_P, {index}))")
        else:
            out.append(f"#define {name} {acc}({name}_P)")
        count += 1
    out += ["", "#endif", ""]
    (PORT / "include" / "globals.h").write_text("\n".join(out))
    print(f"include/globals.h: {count} globals")


if __name__ == "__main__":
    main()
