"""Write build/adapters.c: how build/replay calls each translated function.

    python3 tools/genadapters.py OUT.c

For every function declared in the port's headers (include/*.h), the adapter reads its
arguments where BCC.EXE's caller put them and stores its result where BCC.EXE returns it:

- the calling convention comes from the original definition in ../bcc20/src: every file
  is compiled -mm -p, so a function is far pascal unless declared near (a 2-byte return
  address) or cdecl (arguments pushed right to left, left on the stack by the callee);
- the argument sizes and the result register come from the port's prototype: u8, i8,
  u16 and i16 arguments take a word (a char is pushed as a word), u32, i32 and farptr two;
  a u8 or i8 result is AL, u16 or i16 AX, u32, i32 or farptr DX:AX.

A function whose original takes or returns values in other registers gets a hand-written
adapter in replay/functions.c, which takes precedence (HAND_FUNCTIONS).
"""
import re
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
BCC20_SRC = PORT.parent / "bcc20" / "src"
SIZE = {"u8": 2, "i8": 2, "u16": 2, "i16": 2, "u32": 4, "i32": 4, "farptr": 4}
RESULT = {"void": None, "u8": "AL", "i8": "AL", "u16": "AX", "i16": "AX",
          "u32": "DXAX", "i32": "DXAX", "farptr": "DXAX"}
PROTO = re.compile(r"^(\w+)\s+(\w+)\s*\(([^)]*)\)\s*;", re.M)


def prototypes():
    out = {}
    for h in sorted((PORT / "include").glob("*.h")):
        for ret, name, params in PROTO.findall(h.read_text()):
            if ret in RESULT:
                types = [] if params.strip() in ("", "void") else \
                    [p.strip().rsplit(None, 1)[0] for p in params.split(",")]
                out[name] = (ret, types, h.name)
    return out


def definitions():
    """name -> (near, cdecl) from the original sources' function definitions"""
    out = {}
    head = re.compile(r"^(?!extern|typedef|static\s+\w[^(]*;)([^;{}()#=\n]*?)\b(\w+)\s*\([^;{]*\)\s*\{", re.M)
    for path in BCC20_SRC.rglob("*.C"):
        text = re.sub(r"/\*.*?\*/", " ", path.read_text(encoding="latin1"), flags=re.S)
        for prefix, name in head.findall(text):
            words = set(prefix.split())
            out.setdefault(name, ("near" in words, "cdecl" in words))
    return out


def main():
    target = Path(sys.argv[1])
    protos, defs = prototypes(), definitions()
    lines = ["/* adapters.c: generated by tools/genadapters.py; do not edit. */",
             '#include "replay.h"']
    lines += [f'#include "{h}"' for h in sorted({h for _, _, h in protos.values()})]
    table = []
    for name, (ret, types, _) in sorted(protos.items()):
        if name not in defs:
            raise SystemExit(f"genadapters: no definition of {name} in ../bcc20/src")
        near, cdecl = defs[name]
        ret_size = 2 if near else 4
        sizes = [SIZE[t] for t in types]
        # offsets from SP at entry: pascal pushes left to right, so the last is lowest
        offs, at = [0] * len(types), ret_size
        order = range(len(types)) if cdecl else reversed(range(len(types)))
        for i in order:
            offs[i] = at
            at += sizes[i]
        args = ", ".join(f"({t})arg{'32' if SIZE[t] == 4 else '16'}(r, {o})" for t, o in zip(types, offs))
        call = f"{name}({args})"
        res = RESULT[ret]
        body = {None: f"{call};", "AL": f"r[R_AX] = (r[R_AX] & 0xFF00) | (u8){call};",
                "AX": f"r[R_AX] = (u16){call};", "DXAX": f"ret32(r, (u32){call});"}[res]
        lines.append(f"static void call_{name}(u16 *r) {{ {body} }}")
        outs = {None: "0", "AL": "OUT_AL", "AX": "OUT(R_AX)", "DXAX": "OUT(R_DX) | OUT(R_AX)"}[res]
        table.append(f'    {{"{name}", call_{name}, {outs}, {at if cdecl else 0}}},')
    lines += ["", "const Function GENERATED_FUNCTIONS[] = {"] + table + ["    {0, 0, 0, 0},", "};", ""]
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
