"""Generate native/stack_table.c, BCC.EXE's stack as native/stack.c models it, from the
measurement tools/record.py --sp makes over the corpus:

    python3 tools/record.py --all --max 1 --per-run 1 --out DIR --sp build/stack.json
    python3 tools/genstack.py build/stack.json

For each translated function: its most common SP drop from a caller (used for a pair never
measured) and, for the eight with a stack check, what its frame holds at the check (the
smallest difference seen: a larger one comes from a call nested deeper than the recorder
follows, measured against an enclosing call; checks seen inside other functions are such
calls too).  For each caller and callee pair BCC.EXE showed: the drop, the most common
where call sites differ.  RMAIN13C's SP at entry depends on the command line, and
native.c computes it as BCC.EXE's start-up code does.
Names that share an address resolve to the one the port defines.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import genadapters   # noqa: E402
import record        # noqa: E402

PORT = Path(__file__).resolve().parents[1]


def most_common(counts):
    return int(max(counts.items(), key=lambda kv: (kv[1], -int(kv[0])))[0])


def main():
    stack = json.loads(Path(sys.argv[1]).read_text())
    mine = genadapters.defined_in_port()
    offsets = record.function_offsets()
    by_off = {}
    for name, off in offsets.items():
        if name in mine:
            by_off.setdefault(off, name)

    def resolve(name):
        if name in mine:
            return name
        return by_off.get(offsets.get(name, -1))

    drops, usual, checks, root = {}, {}, {}, None
    for callee, callers in stack["drop"].items():
        c = resolve(callee)
        if not c:
            continue
        for caller, counts in callers.items():
            k = resolve(caller)
            if not k:
                continue
            merged = drops.setdefault((c, k), {})
            for drop, n in counts.items():
                merged[drop] = merged.get(drop, 0) + n
            for drop, n in counts.items():
                usual.setdefault(c, {})[drop] = usual.setdefault(c, {}).get(drop, 0) + n
    for name, counts in stack["check"].items():
        n = resolve(name)
        if n:
            checks[n] = min(int(d) for d in counts)
    for name, counts in stack["root"].items():
        if resolve(name) == "RMAIN13C":
            root = most_common(counts)
    checked = {"LOWER_EXPR_TREE", "STEVALN", "PARSE_DECLARATOR_TREE", "SIMPLIFY_NODE",
               "ANALYZE_EXPRESSION", "SUBSTITUTE_PARAMETERS", "GENERATE_EXPRESSION",
               "FOLD_EXPRESSION"}
    checks = {n: v for n, v in checks.items() if n in checked}

    names = sorted(set(usual) | set(checks) | {k for _, k in drops} | {"RMAIN13C"})
    index = {n: i for i, n in enumerate(names)}
    out = ["/* stack_table.c: generated by tools/genstack.py from tools/record.py --sp (BCC.EXE's",
           "   stack measured over the corpus); native/stack.c says how it is used.  Do not edit. */",
           '#include "port.h"', '#include "protos.h"', '#include "stack_table.h"', "",
           "const StackFunction STACK_FUNCTIONS[] = {"]
    for n in names:
        u = most_common(usual[n]) if n in usual else 0x10
        out.append(f"    {{(void *){n}, 0x{u:X}, 0x{checks.get(n, 0):X}}},")
    out += ["};", f"const int STACK_FUNCTION_COUNT = {len(names)};", "",
            "const StackDrop STACK_DROPS[] = {"]
    for (c, k), counts in sorted(drops.items()):
        out.append(f"    {{{index[c]}, {index[k]}, 0x{most_common(counts):X}}},   /* {c} from {k} */")
    out += ["};", f"const int STACK_DROP_COUNT = {len(drops)};", ""]
    (PORT / "native" / "stack_table.c").write_text("\n".join(out))
    print(f"native/stack_table.c: {len(names)} functions, {len(drops)} pairs, "
          f"{len(checks)} checks; RMAIN13C most often entered with SP {root:04X}")


if __name__ == "__main__":
    main()
