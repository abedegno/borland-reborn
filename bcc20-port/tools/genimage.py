"""Generate native/image.c: the parts of BCC.EXE's program image the native build reads, so
that build/bcc runs without BCC.EXE (README.md, "Use").  The translations read only:

- DGROUP's initial data (paragraph 0DEFh of the load module, up to BSS_START), BCC's
  global data: src/data/DGROUP.ASM in ../bcc20;
- the inline assembler's tables, which INLINASM.ASM keeps in its code segment (paragraphs
  0775h to 0970h: keyword and mnemonic hash tables, operator and form tables);
- the stub header of the message image (paragraph 0C5Bh), which says where in the overlay
  area the message texts lie, and those texts (OVR_ENSURE_IMAGE_LOADED).

That this is all is shown by running the corpus with the rest of the image filled with
F4h: the output is the same.  The image's relocations that fall in these ranges are kept,
and native.c applies them where it loads the parts.

    python3 tools/genimage.py [BCC.EXE]     (default: the toolchain's, ../bcc20/toolchain)
"""
import struct
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[1]
DEFAULT_EXE = PORT.parent / "bcc20" / "toolchain" / "BC20" / "BIN" / "BCC.EXE"
DGROUP_PARA = 0x0DEF
BSS_START = 0x5C96
PARTS = [("IMAGE_INLINASM", 0x0775, 0x0971 * 16 - 0x0775 * 16),
         ("IMAGE_MESSAGE_STUB", 0x0C5B, 0x20),
         ("IMAGE_DGROUP", DGROUP_PARA, BSS_START)]


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    return "\n".join(lines)


def main():
    exe = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_EXE
    d = exe.read_bytes()
    word = lambda o: struct.unpack_from("<H", d, o)[0]
    header = word(8) * 16
    load_end = word(4) * 512 - ((512 - word(2)) if word(2) else 0)
    overlay_base = load_end + (16 if d[load_end:load_end + 4] == b"FBOV" else 0)
    relocs = []
    for i in range(word(6)):
        off, seg = struct.unpack_from("<HH", d, word(0x18) + i * 4)
        relocs.append(seg * 16 + off)
    out = ["/* image.c: generated by tools/genimage.py from BCC.EXE (Borland C++ 2.0, released as",
           "   freeware).  The parts of the program image the native build reads; tools/genimage.py",
           "   says which and why.  Do not edit. */",
           '#include "port.h"', '#include "image.h"', ""]
    table = []
    for name, para, size in PARTS:
        start = para * 16
        data = d[header + start:header + start + size]
        inside = [r - start for r in relocs if start <= r < start + size - 1]
        out.append(f"static const u8 {name}[0x{size:X}] = {{\n{c_bytes(data)}\n}};")
        out.append(f"static const u16 {name}_RELOCS[] = {{" +
                   ", ".join(f"0x{r:X}" for r in inside) + (", " if inside else "") + "0xFFFF};")
        out.append("")
        table.append(f"    {{0x{para:04X}, {name}, sizeof {name}, {name}_RELOCS}},")
    stub = d[header + 0x0C5B * 16:header + 0x0C5B * 16 + 0x20]
    msg_off, msg_size = struct.unpack_from("<I", stub, 4)[0], struct.unpack_from("<H", stub, 8)[0]
    messages = d[overlay_base + msg_off:overlay_base + msg_off + msg_size]
    out.append(f"static const u8 IMAGE_MESSAGES[0x{msg_size:X}] = {{\n{c_bytes(messages)}\n}};")
    out += ["", "const ImagePart IMAGE_PARTS[] = {", *table, "    {0, 0, 0, 0}", "};", "",
            "/* the message image, at this offset of the overlay area */",
            f"const ImageOverlay IMAGE_OVERLAYS[] = {{\n    {{0x{msg_off:X}, IMAGE_MESSAGES, sizeof IMAGE_MESSAGES}},",
            "    {0, 0, 0}", "};", ""]
    (PORT / "native" / "image.c").write_text("\n".join(out))
    print(f"native/image.c: {sum(p[2] for p in PARTS)} bytes of the load module, "
          f"{msg_size} of messages, {sum(1 for r in relocs for _, p, s in PARTS if p * 16 <= r < p * 16 + s - 1)} relocations")


if __name__ == "__main__":
    main()
