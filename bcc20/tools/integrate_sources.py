def compare(left, right):
    a, b = left.read_bytes(), right.read_bytes()
    return sum(x != y for x, y in zip(a, b)) + abs(len(a) - len(b))


def corrected_group_marker(response, group, integrated_groups):
    """Keep a group's already substituted C/assembly sequence intact."""
    marker = fr"H:\{group}.OBJ +"
    if group in integrated_groups:
        if marker in response:
            raise ValueError(f"Integrated group still has original entry: {group}")
        return None
    if response.count(marker) != 1:
        raise ValueError(f"Corrected assembly entry not found: {group}")
    return marker


def omit_empty_overlay_placeholders(response, native_dir=None):
    """Avoid redundant modules in TLINK's limited conventional-memory tables.

    The five CZ objects add no contents or symbols. OVRORDER has already
    introduced their identical empty CODE segments in the required order;
    _DATA/_BSS and their DGROUP membership are shared by the native groups.
    Validate this narrow case on every link, and keep native inputs intact.
    """
    import omf
    native_dir = Path(native_dir) if native_dir is not None else ROOT / "groupobj"
    objects, comma, rest = response.partition(",")
    candidates = [f"CZ{n:03d}" for n in range(5)
                  if fr"H:\CZ{n:03d}.OBJ +" in objects]
    if not candidates:
        return response
    order_marker = r"H:\OVRORDER.OBJ +"
    if objects.count(order_marker) != 1:
        raise ValueError("Missing unique overlay order carrier")

    def signatures(raw, label):
        rr = records(raw)
        if not rr or any(sum(r) & 255 for r in rr):
            raise ValueError(f"Invalid {label} OMF checksums")
        segs = omf.module(raw)[1]
        attrs = [r[3] for r in rr if r[0] == 0x98]
        if len(segs) != len(attrs):
            raise ValueError(f"Unsupported {label} segment definitions")
        return rr, [(name, cls, size, attr) for (name, cls, size), attr in zip(segs, attrs)]

    _, ordered = signatures((native_dir / "OVRORDER.OBJ").read_bytes(), "order carrier")
    for name in candidates:
        marker = fr"H:\{name}.OBJ +"
        if objects.count(marker) != 1 or objects.index(order_marker) > objects.index(marker):
            raise ValueError("Overlay order carrier must precede unique placeholder")
        raw = (native_dir / f"{name}.OBJ").read_bytes()
        # These immutable native placeholders are the only proven omission.
        # Pin all records too: comments may carry linker directives, and OMF
        # group/overlay name indexes have semantics beyond the segment tuple.
        native_pins = {'CZ000': 'c6dfbdc1b66ae01c06eb9562f125fece762f9a608d543805f56de66fa36d6f21', 'CZ001': '372accc3466fba11bbdd82180d0e5d6c20a10969ebef79b173c6b5b51158bc6c', 'CZ002': '680975478173d8ad9cbdeae73cc3d37e41146a995a3eaec706422c6721acaefd', 'CZ003': '1eda7d5ae58444a3798b15727d428bacc5bfc7a74130b8b5a2572b29c72e1c93', 'CZ004': 'b4310a22de0f7791945eb70b3bc24fb232871edcb1101a39b7ba39fab1a9ef2d'}
        if hashlib.sha256(raw).hexdigest() != native_pins[name]:
            raise ValueError(f"Changed native overlay placeholder: {name}")
        rr, sigs = signatures(raw, "placeholder")
        expected = [("_DATA", "DATA", 0, 0x68), ("_BSS", "DATA", 0, 0x48),
                    (f"{name}_TEXT", "CODE", 0, 0x28)]
        if (sigs != expected or any(r[0] not in (0x80, 0x88, 0x96, 0x98, 0x9A, 0x8A) for r in rr)
                or [bytes(r[3:-1]) for r in rr if r[0] == 0x9A] != [bytes.fromhex("08ff02ff01")]
                or rr[-1][0] != 0x8A or bytes(rr[-1][3:-1]) != b"\0"):
            raise ValueError(f"Changed/nonempty overlay placeholder: {name}")
        if ordered.count(expected[-1]) != 1:
            raise ValueError(f"Overlay order carrier no longer owns {name}")
        objects = objects.replace(marker, "")
    return objects + comma + rest


def stage_short_link_inputs(response, source_dirs, destination):
    """Freeze identical ordered objects under short, unqualified DOS names.

    Parse the entire object field: an unlisted filename or nested response must
    never reach TLINK outside the frozen proof. Output/library fields stay exact.
    All copied inputs are refreshed, atomically replaced, and rechecked together.
    """
    import tempfile
    objects, comma, rest = response.partition(",")
    if not comma:
        raise ValueError("Link response lacks output fields")
    references = []
    expecting_object = True
    overlay_open = False
    directive_pending = False
    for token in re.finditer(r"\s+|\+|[^\s+]+", objects):
        value = token.group(0)
        if value.isspace():
            continue
        if not references and value in ("/c", "/m", "/ye"):
            continue
        if value in ("/o", "/o-"):
            if (not references or not expecting_object or directive_pending
                    or (value == "/o") == overlay_open):
                raise ValueError(f"Misplaced overlay link input directive: {value}")
            overlay_open = value == "/o"
            directive_pending = True
            continue
        if value == "+":
            if expecting_object:
                raise ValueError("Invalid link input separator")
            expecting_object = True
            continue
        match = re.fullmatch(r"([A-Za-z]):\\(.+)", value)
        if not expecting_object or not match:
            raise ValueError(f"Unsupported link input: {value}")
        drive, filename = match.groups()
        drive = drive.upper()
        if drive not in source_dirs:
            raise ValueError(f"Unknown link input drive: {drive}")
        if not re.fullmatch(r"[A-Za-z0-9_@$?]{1,8}\.OBJ", filename, re.I):
            raise ValueError(f"Invalid DOS link input: {filename}")
        references.append((token.start(), token.end(), drive, filename))
        directive_pending = False
        expecting_object = False
    if not references or expecting_object or overlay_open:
        raise ValueError("Link response has no complete object inputs")
    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    source_roots = {drive: Path(path).resolve() for drive, path in source_dirs.items()}
    if destination.resolve() in source_roots.values():
        raise ValueError("DOS staging directory must differ from input directories")
    snapshots = []
    for index, (start, end, drive, filename) in enumerate(references):
        source_dir = source_roots[drive]
        source = source_dir / filename
        if source.resolve().parent != source_dir:
            raise ValueError(f"Escaping DOS link input: {filename}")
        short = f"{index:03X}.OBJ"
        if len(short) > 12:
            raise ValueError("Too many DOS link inputs")
        target = destination / short
        if target.is_symlink():
            raise ValueError(f"DOS staging symlink: {short}")
        raw = source.read_bytes()
        snapshots.append((start, end, short, raw))
    proof = []
    chunks = []
    position = 0
    for start, end, short, raw in snapshots:
        target = destination / short
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=destination, delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(raw)
            os.replace(temporary, target)  # replace the directory entry; never follow a link
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
        proof.append(dict(source=objects[start:end], short=short,
                          size=len(raw), sha256=hashlib.sha256(raw).hexdigest()))
        chunks.extend((objects[position:start], short))
        position = end
    for entry in proof:
        target = destination / entry["short"]
        if target.is_symlink() or hashlib.sha256(target.read_bytes()).hexdigest() != entry["sha256"]:
            raise ValueError("Link input staging changed object bytes")
    chunks.append(objects[position:])
    return "".join(chunks) + comma + rest, proof


def pad_tlink_object_counter(response):
    """Avoid TLINK 4.0's byte filename counter wrapping to an empty list.

    The original parser increments DS:0153 for each filename and tests that
    byte for zero after reading the object field. An empty OMF module changes
    this count without contributing segments, symbols, relocations or bytes.
    """
    objects, separator, rest = response.partition(",")
    count = len(re.findall(r"\b[A-Z]:\\[^\s+,]+\.OBJ\b", objects, re.I))
    if not separator or not count or count % 256:
        return response, False
    return objects + " +\nJ:\\ARGPAD.OBJ," + rest, True


def tlink_counter_padding_object():
    """A header and ordinary MODEND, with no allocated or emitted contents."""
    return rebuild(0x80, b"\x06ARGPAD") + rebuild(0x8A, b"\x00")


def validate_link_output(exit_code, log, executable):
    """Discard a failed link's partial EXE before the exact-image gate sees it."""
    duplicate_suffix = r"defined in module G:\ORDERC.ASM is duplicated in module G:\DDATAC.ASM"
    unexpected_errors = [line for line in log.splitlines()
                         if line.startswith("Error:")
                         and not (line.startswith("Error: BCC_")
                                  and line.endswith(duplicate_suffix))]
    if exit_code or unexpected_errors or not executable.exists():
        executable.unlink(missing_ok=True)
        raise SystemExit("Integrated TLINK failed")


def write_exeinfo(exe_path, original_info, out_path):
    """The linked EXE's segment table (TLINK's own, before the overlay repack), in the format of
    original-exeinfo.csv: the same entries at the same file offsets, each four words (segment,
    size, flags, aux).  The repack reads its overlay rows to find the rebuilt overlay stubs."""
    data = Path(exe_path).read_bytes()
    with Path(original_info).open(newline="") as stream:
        rows = list(csv.DictReader(stream))
    lines = ["index,file_offset,segment,size,flags,aux"]
    for row in rows:
        offset = int(row["file_offset"], 16)
        segment, size, flags, aux = struct.unpack_from("<4H", data, offset)
        lines.append(f"{row['index']},{row['file_offset']},{segment:04X},{size},{flags},{aux}")
    Path(out_path).write_text("\n".join(lines) + "\n")


