def records(data):
    result = []
    position = 0
    while position < len(data):
        if position + 3 > len(data):
            raise ValueError("Truncated OMF record header")
        length = int.from_bytes(data[position + 1:position + 3], "little")
        end = position + length + 3
        if end > len(data):
            raise ValueError("Truncated OMF record")
        result.append(bytearray(data[position:end]))
        position = end
    return result


def rebuild(record_type, payload):
    record = bytearray((record_type,)) + (len(payload) + 1).to_bytes(2, "little") + payload
    record.append((-sum(record)) & 0xFF)
    return record


def encode_names(names):
    payload = bytearray()
    for name in names:
        encoded = name.encode("ascii")
        if len(encoded) > 255:
            raise ValueError(f"OMF name is too long: {name}")
        payload.append(len(encoded))
        payload.extend(encoded)
    return payload


def decode_names(payload):
    result = []
    position = 0
    while position < len(payload):
        length = payload[position]
        end = position + 1 + length
        if end > len(payload):
            raise ValueError("Truncated OMF name")
        result.append(bytes(payload[position + 1:end]).decode("ascii"))
        position = end
    return result


def rewrite_named_record(record, replacements):
    names = decode_names(record[3:-1])
    names = [replacements.get(name.upper(), name) for name in names]
    return rebuild(record[0], encode_names(names))


def rewrite_external_record(record, replacements, extra_names=()):
    payload = bytearray()
    position = 3
    while position < len(record) - 1:
        length = record[position]
        end = position + 1 + length
        name = bytes(record[position + 1:end]).decode("ascii")
        replacement = replacements.get(normalized(name), name).encode("ascii")
        payload.append(len(replacement))
        payload.extend(replacement)
        _, position = read_index(record[:-1], end)
        payload.extend(record[end:position])
    for name in extra_names:
        encoded = name.encode("ascii")
        payload.append(len(encoded))
        payload.extend(encoded)
        payload.append(0)
    return rebuild(record[0], payload)


def read_index(payload, position):
    """Decode OMF's tagged one- or two-byte index, not a little-endian word."""
    if position >= len(payload):
        raise ValueError("Truncated OMF index")
    first = payload[position]
    if not first & 0x80:
        return first, position + 1
    if position + 1 >= len(payload):
        raise ValueError("Truncated OMF index")
    return ((first & 0x7F) << 8) | payload[position + 1], position + 2


def encode_index(index):
    if not 0 <= index <= 0x7FFF:
        raise ValueError(f"OMF index out of range: {index}")
    if index < 128:
        return bytes((index,))
    return bytes((0x80 | (index >> 8), index & 0xFF))


def index_size(payload, position):
    return read_index(payload, position)[1] - position


def ledata_layout(record):
    """Return the segment, segment-relative start, and raw data position."""
    if record[0] != 0xA0:
        raise ValueError("Expected 16-bit LEDATA")
    segment, position = read_index(record[:-1], 3)
    if position + 2 > len(record) - 1:
        raise ValueError("Truncated LEDATA offset")
    start = int.from_bytes(record[position:position + 2], "little")
    return segment, start, position + 2


def code_segment_index(object_records):
    """Select the populated 16-bit CODE segment, ignoring external declarations."""
    unsupported = {0x99, 0x91, 0x9D, 0xA1, 0xA2, 0xA3}
    if any(record[0] in unsupported for record in object_records):
        raise ValueError("Only 16-bit SEGDEF/PUBDEF/FIXUPP/LEDATA objects are supported")
    names = [name for record in object_records if record[0] == 0x96
             for name in decode_names(record[3:-1])]
    code = []
    segments = [record for record in object_records if record[0] == 0x98]
    for index, record in enumerate(segments, 1):
        payload = record[3:-1]
        if not payload:
            raise ValueError("Truncated SEGDEF")
        if payload[0] & 1:
            raise ValueError("32-bit USE32 segments are not supported")
        length_position = 1 + (3 if payload[0] >> 5 == 0 else 0)
        if length_position + 2 > len(payload):
            raise ValueError("Truncated SEGDEF length")
        length = int.from_bytes(payload[length_position:length_position + 2], "little")
        position = length_position + 2
        _, position = read_index(payload, position)  # segment name
        class_index, position = read_index(payload, position)
        _, position = read_index(payload, position)  # overlay name
        if not 0 < class_index <= len(names):
            raise ValueError("Invalid SEGDEF class index")
        if names[class_index - 1].upper() == "CODE" and (length or payload[0] & 2):
            code.append(index)
    # Standalone FIXUPP test fragments have no segment declarations. Borland's
    # first segment is CODE; full objects must identify it through their class.
    if not segments:
        return 1
    if len(code) != 1:
        raise ValueError(f"Expected one CODE segment, found {len(code)}")
    return code[0]


def code_segment_name(object_records):
    """Keep the native combine identity, including resident library names."""
    segment = code_segment_index(object_records)
    definitions = [record for record in object_records if record[0] == 0x98]
    if not 0 < segment <= len(definitions):
        raise ValueError("Missing native CODE SEGDEF")
    names = [name for record in object_records if record[0] == 0x96
             for name in decode_names(record[3:-1])]
    payload = definitions[segment - 1][3:-1]
    position = 3 + (3 if payload[0] >> 5 == 0 else 0)
    name, _ = read_index(payload, position)
    if not 0 < name <= len(names) or not names[name - 1]:
        raise ValueError("Invalid native CODE segment name")
    return names[name - 1]


def native_group_code_name(group):
    return code_segment_name(records((ROOT / "groupobj" / f"{group}.OBJ").read_bytes()))


def fixup_subrecords(payload, target_threads):
    """Parse 16-bit FIXUPP subrecords, retaining thread state across records."""
    def datum(position, method):
        if method < 3:
            return read_index(payload, position)
        if method == 3:
            if position + 2 > len(payload):
                raise ValueError("Truncated absolute OMF frame")
            return int.from_bytes(payload[position:position + 2], "little"), position + 2
        return None, position

    position = 0
    while position < len(payload):
        start = position
        control = payload[position]
        if not control & 0x80:
            position += 1
            method = (control >> 2) & 7
            index, position = datum(position, method)
            if not control & 0x40:
                target_threads[control & 3] = (method, index)
            yield start, position, None, None, None, None, None, None
            continue
        if position + 3 > len(payload):
            raise ValueError("Truncated OMF fixup")
        location = int.from_bytes(payload[position:position + 2], "big")
        fixdata = payload[position + 2]
        position += 3
        if not fixdata & 0x80:
            _, position = datum(position, (fixdata >> 4) & 7)
        target_position = position
        if fixdata & 8:
            thread = target_threads[fixdata & 3]
            if thread is None:
                raise ValueError("Undefined OMF target thread")
            method, target = thread
        else:
            method = fixdata & 3
            target, position = datum(position, method)
        target_size = position - target_position
        if not fixdata & 4:
            position += 2
        if position > len(payload):
            raise ValueError("Truncated OMF target displacement")
        yield start, position, location, fixdata, method, target, target_position, target_size


def sorted_fixup_record(record, near_offsets=frozenset(), target_overrides=None,
                        remove_offsets=frozenset(), native_near_offsets=frozenset(),
                        segment_fixups=None, offset_shift=0, data_base=0,
                        max_offset=None, target_threads=None):
    """Apply segment-relative decisions while encoding LEDATA-local positions."""
    target_overrides = target_overrides or {}
    payload = bytes(record[3:-1])
    if target_threads is None:
        target_threads = [None] * 4
    entries = []
    has_threads = False
    for start, end, location, fixdata, method, target, target_position, target_size in fixup_subrecords(payload, target_threads):
        if location is None:
            has_threads = True
            entries.append((None, payload[start:end]))
            continue
        has_threads |= bool(fixdata & 0x88)
        local_offset = (location & 0x3FF) + offset_shift
        offset = data_base + local_offset
        if max_offset is not None and offset >= max_offset:
            continue
        widths = {0: 1, 1: 2, 2: 2, 3: 4, 4: 1, 5: 2}
        location_type = (location >> 10) & 15
        if location_type not in widths:
            raise ValueError(f"Unsupported OMF location type {location_type}")
        if max_offset is not None and offset + widths[location_type] > max_offset:
            raise ValueError("OMF fixup straddles the retained code boundary")
        if not 0 <= local_offset < 0x400:
            raise ValueError("OMF fixup exceeds its 10-bit LEDATA-local offset")
        if segment_fixups and offset in segment_fixups:
            target_method, target_index = segment_fixups[offset]
            if local_offset + 2 >= 0x400:
                raise ValueError("Segment fixup exceeds its LEDATA-local offset")
            entries.append((offset + 2, (0xC800 | (local_offset + 2)).to_bytes(2, "big")
                            + bytes((0x54 | target_method,)) + encode_index(target_index)))
            continue
        if offset in remove_offsets:
            continue
        encoded = payload[start:end]
        if offset_shift:
            encoded = ((location & 0xFC00) | local_offset).to_bytes(2, "big") + encoded[2:]
        replacement = target_overrides.get((offset, target))
        if replacement is not None:
            if not target_size or method != 2:
                raise ValueError("Cannot retarget a threaded or non-external OMF fixup")
            relative = target_position - start
            encoded = encoded[:relative] + encode_index(replacement) + encoded[relative + target_size:]
        if offset in native_near_offsets:
            encoded = (0x8400 | local_offset).to_bytes(2, "big") + encoded[2:]
        elif offset in near_offsets:
            if local_offset + 2 >= 0x400:
                raise ValueError("Near fixup exceeds its LEDATA-local offset")
            encoded = (0x8400 | (local_offset + 2)).to_bytes(2, "big") + encoded[2:]
        entries.append((offset, encoded))
    if not has_threads:
        entries.sort(key=lambda item: item[0])
    return rebuild(record[0], b"".join(item[1] for item in entries))


def normalized(name):
    name = name.upper()
    if name.startswith("_"):
        name = name[1:]
    return name


def validate_external_name_keys(names):
    seen = {}
    for name in names:
        key = normalized(name)
        if key in seen and seen[key] != name:
            raise ValueError(f"Ambiguous normalized external names: {seen[key]} and {name}")
        seen[key] = name


def canonical_symbol_addresses(entries):
    result = {}
    seen = {}
    for name, text in entries:
        key = normalized(name)
        address = format_address(parse_address(text))
        if key in seen and (seen[key] != name or result[key] != address):
            raise ValueError(f"Ambiguous normalized symbol names: {seen[key]} and {name}")
        seen[key] = name
        result[key] = address
    return result


def external_names(object_records):
    result = []
    for record in object_records:
        if record[0] != 0x8C:
            continue
        position = 3
        while position < len(record) - 1:
            length = record[position]
            end = position + 1 + length
            result.append(bytes(record[position + 1:end]).decode("ascii"))
            _, position = read_index(record[:-1], end)
    return result


def external_fixups(object_records):
    """Map EXTDEF names to offsets in the object's CODE segment only."""
    names = external_names(object_records)
    code_segment = code_segment_index(object_records)
    result = defaultdict(list)
    data_segment = None
    data_base = 0
    target_threads = [None] * 4
    for record in object_records:
        if record[0] == 0xA0:
            data_segment, data_base, _ = ledata_layout(record)
        if record[0] != 0x9C:
            continue
        for _, _, location, _, method, target, _, _ in fixup_subrecords(
                bytes(record[3:-1]), target_threads):
            if (location is not None and data_segment == code_segment
                    and method == 2 and 0 < target <= len(names)):
                result[names[target - 1]].append(data_base + (location & 0x3FF))
    return result


def public_offsets(object_records):
    result = {}
    code_segment = code_segment_index(object_records)
    for record in object_records:
        if record[0] != 0x90:
            continue
        payload = record[3:-1]
        _, position = read_index(payload, 0)  # group
        segment, position = read_index(payload, position)
        if segment != code_segment:
            continue
        while position < len(payload):
            length = payload[position]
            end = position + 1 + length
            if end + 2 > len(payload):
                raise ValueError("Truncated PUBDEF")
            name = bytes(payload[position + 1:end]).decode("ascii")
            offset = int.from_bytes(payload[end:end + 2], "little")
            _, position = read_index(payload, end + 2)  # type index
            result[offset] = name
    return result


def listing_lines(path):
    result = {}
    pattern = re.compile(r"^\s*\d+\t([0-9A-Fa-f]{4})\s+([^\t]*)\t(.*)$")
    continuation = re.compile(r"^\s*\d+\t\s+([0-9A-Fa-f ]+?)(?:\t([^\t]*))?$")
    last_address = None
    for line in path.read_text(errors="replace").splitlines():
        match = pattern.match(line)
        if match:
            last_address = int(match.group(1), 16)
            byte_text = match.group(2).strip()
            second_column = match.group(3).split("\t", 1)[0].strip()
            for token in second_column.split():
                if re.fullmatch(r"[0-9A-Fa-f]{2}\+?", token):
                    byte_text += " " + token.removesuffix("+")
            result[last_address] = (byte_text, match.group(3).strip())
            continue
        match = continuation.match(line)
        if match and last_address is not None:
            extra = match.group(1).strip()
            tail = (match.group(2) or "").strip().split()
            if tail and re.fullmatch(r"[0-9A-Fa-f]{2}", tail[0]):
                extra += " " + tail[0]
            byte_text, assembly = result[last_address]
            result[last_address] = (byte_text + " " + extra, assembly)
    return result


def listing_fields(text):
    """Return machine-byte fields with their relocation markers and offsets."""
    result = []
    cursor = 0
    for token in text.split():
        external = len(token) == 5 and token[-1] in "eEsS"
        if external:
            token = token[:-1]
        token = token.removesuffix(":")
        if len(token) == 2:
            value = bytes((int(token, 16),))
        elif len(token) == 4:
            value = int(token, 16).to_bytes(2, "little")
        else:
            break
        result.append((cursor, external, value))
        cursor += len(value)
    return result


def listing_machine_bytes(text):
    return b"".join(value for _, _, value in listing_fields(text))


def listing_field(text, offset):
    return next((field for field in listing_fields(text) if field[0] == offset), None)


def listing_bytes_at(lines, address, size, addresses=None):
    """Read a machine-byte window even when TASM wraps or splits DB lines."""
    addresses = sorted(lines) if addresses is None else addresses
    result = bytearray()
    for position in range(address, address + size):
        index = bisect_right(addresses, position) - 1
        if index < 0:
            return None
        start = addresses[index]
        data = listing_machine_bytes(lines[start][0])
        offset = position - start
        if offset >= len(data):
            return None
        result.append(data[offset])
    return bytes(result)


def near_call_fixups(group, module_base, object_records):
    """Find C far-call fixups whose original instruction is a near call."""
    lines = listing_lines(ROOT / "groupobj" / f"{group}.LST")
    result = {}
    for name, fixups in external_fixups(object_records).items():
        selected = []
        for fixup in fixups:
            address = module_base + fixup
            if address not in lines or address + 1 not in lines:
                continue
            if (listing_machine_bytes(lines[address][0]) == b"\x0E"
                    and listing_machine_bytes(lines[address + 1][0])[:1] == b"\xE8"):
                selected.append(fixup)
        if selected:
            result[name] = selected
    return result


def offset_aliases(group, module_base, object_records):
    """Resolve each C external occurrence from its original instruction."""
    lines = listing_lines(ROOT / "groupobj" / f"{group}.LST")
    addresses = sorted(lines)
    publics = public_offsets(records((ROOT / "groupobj" / f"{group}.OBJ").read_bytes()))
    local_procs = {}
    listing_text = (ROOT / "groupobj" / f"{group}.LST").read_text(errors="replace")
    for match in re.finditer(
            r"^\s*\d+\t([0-9A-Fa-f]{4})\s+[^\t]*\t[ \t]*"
            r"([A-Za-z_@$?][\w@$?]*)\s+(?:proc|label)\s+near\b", listing_text, re.I | re.M):
        local_procs[int(match.group(1), 16)] = match.group(2)
    occurrences = []
    for name, fixups in external_fixups(object_records).items():
        for fixup in fixups:
            address = module_base + fixup
            preceding = [item for item in addresses if item <= address]
            if not preceding:
                continue
            instruction_address = preceding[-1]
            byte_text, assembly = lines[instruction_address]
            byte_values = listing_machine_bytes(byte_text)
            if byte_values == b"\x0E" and address + 1 in lines:
                instruction_address = address + 1
                byte_text, assembly = lines[instruction_address]
                byte_values = listing_machine_bytes(byte_text)
            if (instruction_address - 1 in lines
                    and listing_machine_bytes(lines[instruction_address - 1][0]) == b"\xE8"):
                instruction_address -= 1
                byte_text, assembly = lines[instruction_address]
                byte_values = listing_machine_bytes(byte_text)
            field = listing_field(byte_text, address - instruction_address)
            window = listing_bytes_at(lines, address - 1, 3, addresses)
            if window is not None and window[0] == 0xE8:
                # A raw gap's relative word can have one byte on each DB line.
                instruction_address = address - 1
                byte_values = window
                field = (1, False, window[1:])
            if (field is not None and field[0] > 0
                    and byte_values[field[0] - 1:field[0]] == b"\xE8"):
                # Raw layout gaps use one db line for several instructions, so
                # a near-call opcode can precede the fixup within the same line.
                opcode_offset = field[0] - 1
                instruction_address += opcode_offset
                byte_values = byte_values[opcode_offset:]
                field = (1, field[1], byte_values[1:3])
            elif field is not None:
                # The opcode can also be the final byte of the preceding db line.
                opcode_address = address - 1
                opcode_lines = [item for item in addresses if item <= opcode_address]
                if opcode_lines:
                    opcode_line = opcode_lines[-1]
                    opcode_bytes = listing_machine_bytes(lines[opcode_line][0])
                    opcode_field = listing_field(lines[opcode_line][0],
                                                 opcode_address - opcode_line)
                    if (opcode_field is not None
                            and opcode_bytes[opcode_field[0]:opcode_field[0] + 1] == b"\xE8"):
                        instruction_address = opcode_address
                        displacement = byte_values[field[0]:field[0] + 2]
                        byte_values = b"\xE8" + displacement
                        field = (1, field[1], displacement)
            occurrences.append((fixup, normalized(name), instruction_address,
                                byte_values, assembly, field))
    by_instruction = defaultdict(list)
    for occurrence in occurrences:
        by_instruction[occurrence[2]].append(occurrence)
    result = defaultdict(dict)
    adjustments = defaultdict(dict)
    literal_offsets = set()
    raw_near = {}
    near_locations = set()
    for instruction_occurrences in by_instruction.values():
        instruction_occurrences.sort()
        for occurrence in instruction_occurrences:
            occurrence_fixup, occurrence_name = occurrence[:2]
            field = occurrence[5]
            next_address = module_base + occurrence_fixup + 1
            # C emits _CTYPE+2 for these byte-table tests, whereas the target
            # uses _CTYPE+1. TASM leaves the word unmarked and can split it
            # either within a raw db statement or across two statements.
            if (occurrence_name == "CTYPE" and field is not None and not field[1]
                    and len(field[2]) == 1):
                following = occurrence[3][field[0] + 1:field[0] + 2]
                if not following and next_address in lines:
                    following = listing_machine_bytes(lines[next_address][0])[:1]
                if following:
                    adjustments[occurrence_name][occurrence_fixup] = int.from_bytes(
                        field[2] + following, "little")
                    literal_offsets.add(occurrence_fixup)
        fixup, name, instruction_address, byte_values, assembly, _ = instruction_occurrences[0]
        if (byte_values[:1] == b"\xE8" and len(byte_values) < 3
                and instruction_address + 1 in lines):
            byte_values += listing_machine_bytes(lines[instruction_address + 1][0])
        if byte_values[:1] == b"\xE8" and len(byte_values) >= 3:
            near_locations.add(fixup)
            displacement = int.from_bytes(byte_values[1:3], "little", signed=True)
            target = instruction_address + 3 + displacement
            if target in publics:
                result[name][fixup] = publics[target]
            elif target in local_procs:
                result[name][fixup] = local_procs[target]
                raw_near[fixup] = displacement
            else:
                # A near call into an unlabelled same-segment gap needs no
                # linker relocation; retain its original displacement.
                result[name][fixup] = name
                raw_near[fixup] = displacement
            continue
        candidates = re.findall(
            r"\b(BCC_[\w@$?]+|X[0-9A-Fa-f]{3}_[0-9A-Fa-f]{2})\b"
            r"(?:\s*([+-])\s*([0-9A-Fa-f]+)(h)?)?", assembly, re.I)
        symbolic = [occurrence for occurrence in instruction_occurrences
                    if occurrence[5] is not None and occurrence[5][1]]
        if len(candidates) != len(symbolic):
            continue
        for occurrence, (target, sign, displacement, hexadecimal) in zip(symbolic, candidates):
            occurrence_fixup, occurrence_name = occurrence[:2]
            result[occurrence_name][occurrence_fixup] = target
            field = occurrence[5]
            if len(field[2]) == 2:
                # Preserve the original OMF addend. This matters when a C
                # symbol+2 reference becomes a separate absolute high-word alias.
                adjustments[occurrence_name][occurrence_fixup] = int.from_bytes(
                    field[2], "little")
    return result, adjustments, raw_near, near_locations, literal_offsets


def offset_constants(group, module_base, object_records):
    """Recover absolute aliases after removing each C immediate's addend."""
    lines = listing_lines(ROOT / "groupobj" / f"{group}.LST")
    addresses = sorted(lines)
    code_segment = code_segment_index(object_records)
    code_records = [(record, start, data_position)
                    for record in object_records if record[0] == 0xA0
                    for segment, start, data_position in [ledata_layout(record)]
                    if segment == code_segment]
    result = {}
    for name, fixups in external_fixups(object_records).items():
        values = set()
        for fixup in fixups:
            address = module_base + fixup
            preceding = [item for item in addresses if item <= address]
            if not preceding:
                continue
            instruction_address = preceding[-1]
            byte_text, assembly = lines[instruction_address]
            if assembly.lower().startswith("db"):
                continue
            field = listing_field(byte_text, address - instruction_address)
            if field is None or field[1] or len(field[2]) != 2:
                continue
            addends = [int.from_bytes(record[data_position + fixup - start:
                                             data_position + fixup - start + 2], "little")
                       for record, start, data_position in code_records
                       if start <= fixup and data_position + fixup - start + 2 <= len(record) - 1]
            if len(addends) == 1:
                values.add((int.from_bytes(field[2], "little") - addends[0]) & 0xFFFF)
        if len(values) == 1:
            result[normalized(name)] = values.pop()
    return result


def raw_far_calls(group, module_base, object_records):
    """Recover direct far calls represented by a literal offset and SEGDEF fixup."""
    lines = listing_lines(ROOT / "groupobj" / f"{group}.LST")
    code_segment = code_segment_index(object_records)
    code_records = [(record, start, data_position)
                    for record in object_records if record[0] == 0xA0
                    for segment, start, data_position in [ledata_layout(record)]
                    if segment == code_segment]
    addresses = sorted(lines)
    result = {}
    for name, fixups in external_fixups(object_records).items():
        for fixup in fixups:
            address = module_base + fixup
            preceding = [item for item in addresses if item <= address]
            if not preceding or address + 2 not in lines:
                continue
            instruction_address = preceding[-1]
            byte_text = lines[instruction_address][0]
            byte_values = listing_machine_bytes(byte_text)
            field = listing_field(byte_text, address - instruction_address)
            opcode_address = address - 1
            opcode_lines = [item for item in addresses if item <= opcode_address]
            opcode_valid = False
            if field is not None and opcode_lines:
                opcode_line = opcode_lines[-1]
                opcode_bytes = listing_machine_bytes(lines[opcode_line][0])
                opcode_field = listing_field(lines[opcode_line][0],
                                             opcode_address - opcode_line)
                opcode_valid = (opcode_field is not None
                                and opcode_bytes[opcode_field[0]:opcode_field[0] + 1] == b"\x9A")
            if not opcode_valid:
                continue
            segment = re.fullmatch(r"dw\s+seg\s+([A-Za-z_@$?][\w@$?]*)",
                                   lines[address + 2][1], re.I)
            if field[1] or len(field[2]) != 2 or segment is None:
                continue
            addends = [int.from_bytes(record[data_position + fixup - start:
                                             data_position + fixup - start + 2], "little")
                       for record, start, data_position in code_records
                       if start <= fixup and data_position + fixup - start + 2 <= len(record) - 1]
            if len(addends) == 1:
                value = (int.from_bytes(field[2], "little") - addends[0]) & 0xFFFF
                result[fixup] = (value, segment.group(1), normalized(name))
    return result


def add_segment_definitions(object_records, segment_names):
    """Add zero-length public SEGDEFs used by direct far-call fixups."""
    result = {}
    for name in sorted(segment_names):
        names = [item for record in object_records if record[0] == 0x96
                 for item in decode_names(record[3:-1])]
        if name in names:
            name_index = names.index(name) + 1
        else:
            name_index = len(names) + 1
            last = max(index for index, record in enumerate(object_records)
                       if record[0] == 0x96)
            record = object_records[last]
            object_records[last] = rebuild(0x96, record[3:-1] + encode_names([name]))
        code_segment = code_segment_index(object_records)
        template = [record for record in object_records if record[0] == 0x98][code_segment - 1]
        payload = bytearray(template[3:-1])
        length_position = 1 + (3 if payload[0] >> 5 == 0 else 0)
        payload[length_position:length_position + 2] = b"\0\0"
        name_position = length_position + 2
        old_size = index_size(payload, name_position)
        encoded_index = encode_index(name_index)
        payload[name_position:name_position + old_size] = encoded_index
        segment_index = 1 + sum(record[0] in (0x98, 0x99) for record in object_records)
        # TASM may emit another LNAMES after the existing SEGDEFs. New
        # definitions must follow the names just appended to that record.
        insert_at = 1 + max(index for index, record in enumerate(object_records)
                            if record[0] in (0x96, 0x98, 0x99))
        object_records.insert(insert_at, rebuild(template[0], payload))
        result[name] = segment_index
    return result


def native_data_publics():
    """Native DDATA public spellings and absolute values, without alias inference."""
    text = (ROOT / "linksrc" / "DDATA.ASM").read_text()
    publics = []
    values = {}
    for line in text.splitlines():
        line = line.split(";", 1)[0].strip()
        public = re.fullmatch(r"public\s+(.+)", line, re.I)
        if public:
            publics.extend(name.strip() for name in public.group(1).split(","))
        absolute = re.fullmatch(
            r"([A-Za-z_@$?][\w@$?]*)\s*(?:=|equ)\s*([0-9A-Fa-f]+h|[0-9]+)", line, re.I)
        if absolute:
            name, number = absolute.groups()
            values[name.upper()] = int(number[:-1], 16) if number.lower().endswith("h") else int(number)
    result = defaultdict(list)
    for name in publics:
        result[normalized(name)].append((name, values.get(name.upper())))
    return result


def alias_mappings(module, block, alias_rows, symbol_addresses):
    direct = {}
    data_targets = {}
    root_targets = {}
    for match in re.finditer(r"^\s*extrn\s+([A-Za-z_@$?][\w@$?]*)\s*:", block, re.I | re.M):
        symbol = match.group(1)
        direct[normalized(symbol)] = symbol
        if normalized(symbol).startswith("BCC_"):
            direct[normalized(symbol)[4:]] = symbol
        raw_data = re.fullmatch(r"BCC_RD_([0-9A-Fa-f]{4})_[BWD]", symbol, re.I)
        if raw_data:
            data_targets[raw_data.group(1).upper()] = symbol
        root = re.fullmatch(r"BCC_RF_([0-9A-Fa-f]{4})_([0-9A-Fa-f]{4})", symbol, re.I)
        if root:
            root_targets[(int(root.group(1), 16) - 0x1000, root.group(2).upper())] = symbol
    aliases = {}
    for row in alias_rows:
        if row["reference"].upper() != module + ".ASM" or not row["canonical"]:
            continue
        symbol = normalized(row["symbol"])
        if symbol.startswith("BCC_"):
            symbol = symbol[4:]
        aliases[symbol] = row["canonical"]
    for name, address in symbol_addresses.items():
        domain = parse_address(address)
        if domain[0] == "DS" and address[3:] in data_targets:
            aliases.setdefault(name, data_targets[address[3:]])
        elif domain[0] == "FAR":
            target = root_targets.get((domain[1], f"{domain[2]:04X}"))
            if target:
                aliases.setdefault(name, target)
    return direct, aliases


def body_native_target(address, caller_index, native_offsets):
    """Resolve a body in the caller's original overlay, never a resident stub."""
    value = parse_address(address)
    if value[0] != "OVL" or value[1] != caller_index:
        raise ValueError("Overlay body reference must share the caller original overlay")
    return native_offsets.get(value[2])


def private_body_target(address, native_names):
    value = parse_address(address)
    if value[0] != "OVL": raise ValueError("Private body requires an overlay body address")
    name = f"COVL_{value[1]:04X}_{value[2]:04X}"
    if name in {normalized(n) for n in native_names}:
        raise ValueError(f"Generated private body name {name} conflicts with a native PUBLIC")
    return name, value[2]


@lru_cache(maxsize=4)
def _native_public_names(files):
    names = set()
    for filename, _, _ in files:
        for record in records(Path(filename).read_bytes()):
            if record[0] not in (0x90, 0x91): continue
            payload = record[3:-1]
            _, pos = read_index(payload, 0)
            segment, pos = read_index(payload, pos)
            if segment == 0: pos += 2
            while pos < len(payload):
                length = payload[pos]
                names.add(normalized(bytes(payload[pos+1:pos+1+length]).decode("ascii")))
                pos += 1 + length + (4 if record[0] == 0x91 else 2)
                _, pos = read_index(payload, pos)
    return frozenset(names)


