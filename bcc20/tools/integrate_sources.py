def prepend_module_prefix(object_records, group, module_base, size):
    """Restore constant bytes before a single compiler-emitted CODE record."""
    if not size:
        return
    code_segment = code_segment_index(object_records)
    code_records = [(index, ledata_layout(record))
                    for index, record in enumerate(object_records) if record[0] == 0xA0
                    and ledata_layout(record)[0] == code_segment]
    if len(code_records) != 1 or code_records[0][1][1] != 0:
        raise ValueError("Module prefixes require one CODE LEDATA record starting at zero")
    prefix = bytearray(size)
    covered = bytearray(size)
    baseline = records((ROOT / "groupobj" / f"{group}.OBJ").read_bytes())
    baseline_code = code_segment_index(baseline)
    for record in baseline:
        if record[0] != 0xA0:
            continue
        segment, start, data_position = ledata_layout(record)
        if segment != baseline_code:
            continue
        data = record[data_position:-1]
        for index in range(size):
            source_offset = module_base + index
            if start <= source_offset < start + len(data):
                prefix[index] = data[source_offset - start]
                covered[index] = 1
    if not all(covered):
        raise ValueError(f"{group}: incomplete {size}-byte module prefix at {module_base:04X}")
    first_index, (_, _, data_position) = code_records[0]
    record = object_records[first_index]
    object_records[first_index] = rebuild(record[0], record[3:data_position] + prefix + record[data_position:-1])
    data_segment = None
    target_threads = [None] * 4
    for index, record in enumerate(object_records):
        if record[0] == 0xA0:
            data_segment = ledata_layout(record)[0]
        elif record[0] == 0x9C:
            if data_segment == code_segment:
                object_records[index] = sorted_fixup_record(
                    record, offset_shift=size, target_threads=target_threads)
            else:
                list(fixup_subrecords(bytes(record[3:-1]), target_threads))


