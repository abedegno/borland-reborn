def validate_native_far_binding_overlaps(object_records, code_segment, bound_indices, *, cs_code_indices=frozenset()):
    """Protect bound CODE fields from every other relocation and payload writer.

    The record associated with a bound FIXUPP owns its component bytes. Even a
    plain earlier/later LEDATA record without fixups can otherwise overwrite
    those adjusted bytes, so disallow any other CODE payload writer there.
    """
    widths = {0: 1, 1: 2, 2: 2, 3: 4, 4: 1, 5: 2}
    associated = None
    target_threads = [None] * 4
    intervals = []
    writers = []
    for record_index, record in enumerate(object_records):
        if record[0] == 0xA0:
            segment, start, position = ledata_layout(record)
            associated = (segment, start, record_index)
            if segment == code_segment:
                writers.append((record_index, start, start + len(record) - position - 1))
        elif record[0] == 0x9C:
            for _, _, location, fixdata, method, target, _, _ in fixup_subrecords(
                    bytes(record[3:-1]), target_threads):
                if location is None or associated is None or associated[0] != code_segment:
                    continue
                offset = associated[1] + (location & 0x3FF)
                width = widths.get((location >> 10) & 15)
                bound = method == 2 and target in bound_indices
                if bound and target in cs_code_indices and (fixdata >> 4) & 7 == 0 and width is not None:
                    # A scoped CS OFFSET16 permission authenticates its three
                    # opcode bytes too; other writers/relocations cannot change
                    # the instruction after its operand is rebound.
                    offset -= 3
                    width += 3
                intervals.append((offset, width, bound, associated[2]))
    if not any(bound for _, _, bound, _ in intervals):
        return
    if any(width is None for _, width, _, _ in intervals):
        raise ValueError("Unknown CODE relocation width beside a FAR native binding")
    for index, (start, width, bound, owner_record) in enumerate(intervals):
        if not bound:
            continue
        for other_index, (other_start, other_width, _, _) in enumerate(intervals):
            if (index != other_index and start < other_start + other_width
                    and other_start < start + width):
                raise ValueError("FAR native binding overlaps another CODE relocation")
        for writer_record, writer_start, writer_end in writers:
            if (writer_record != owner_record and writer_start < writer_end
                    and start < writer_end and writer_start < start + width):
                raise ValueError("FAR native binding overlaps another CODE LEDATA writer")


def apply_native_far_bindings(object_records, module, symbol_addresses,
                              bindings, module_size):
    """Rebase only explicitly bound CODE external FAR components.

    The audited native_base is an original native MAP identity. Canonical C
    identity must still match strict-verified symbols exactly. This does not
    discover names, insert exports, or infer address domains from instructions.
    Unsupported bound references fail closed; unbound records stay untouched.
    """
    declarations = bindings.get(module, {})
    if not declarations:
        return object_records, {}, set()
    names = external_names(object_records)
    validate_external_name_keys(names)
    known = {}
    for key, binding in declarations.items():
        base = normalized(key)
        if base in known:
            raise ValueError(f"{module}: duplicate normalized FAR native binding")
        expected = parse_address(binding["expected"])
        native_base = parse_address(binding["native_base"])
        if expected[0] != "FAR" or native_base[0] != "FAR":
            raise ValueError(f"{module}: FAR native binding requires resident FAR identities")
        offset, paragraph = binding["offset_delta"], binding["paragraph_delta"]
        if (type(offset) is not int or not -0xFFFF <= offset <= 0xFFFF
                or type(paragraph) is not int or not 0 <= paragraph <= 0xFFFF):
            raise ValueError(f"{module}: invalid FAR native component delta")
        if (native_base[1] + paragraph > 0xFFFF
                or not 0 <= native_base[2] + offset <= 0xFFFF
                or expected != ("FAR", native_base[1] + paragraph,
                                 native_base[2] + offset)):
            raise ValueError(f"{module}: FAR native component arithmetic disagrees")
        cs_code = binding.get("allow_cs_code_frame", False)
        if type(cs_code) is not bool or cs_code and (offset < 0 or paragraph != 0):
            raise ValueError(f"{module}: invalid CS CODE frame capability/delta")
        native = binding["native"]
        if not isinstance(native, str) or not re.fullmatch(r"[A-Za-z_@$?][\w@$?]*", native):
            raise ValueError(f"{module}: invalid FAR native target name")
        known[base] = binding
    active = {}
    for index, name in enumerate(names, 1):
        key = normalized(name)
        if key not in known:
            continue
        binding = known[key]
        canonical = symbol_addresses.get(key)
        if canonical is None or parse_address(canonical) != parse_address(binding["expected"]):
            raise ValueError(f"{module}: canonical FAR source identity disagrees for {key}")
        active[index] = (key, binding)
    if not active:
        return object_records, {}, set()
    if any(record[0] in (0x99, 0xA1, 0x9D) for record in object_records):
        raise ValueError(f"{module}: FAR native bindings support only 16-bit OMF")
    output = list(object_records)
    code_segment = code_segment_index(object_records)
    validate_native_far_binding_overlaps(object_records, code_segment, active,
        cs_code_indices={index for index, (_, binding) in active.items()
                         if binding.get("allow_cs_code_frame", False)})
    associated = None
    targets = [None] * 4
    positions, consumed, intervals = set(), set(), []
    for ri, record in enumerate(object_records):
        if record[0] == 0xA0:
            segment, start, position = ledata_layout(record)
            associated = (ri, segment, start, position)
        elif record[0] == 0x9C:
            payload = bytes(record[3:-1])
            for first, last, location, fixdata, method, target, _, _ in fixup_subrecords(payload, targets):
                if location is None or method != 2 or target not in active:
                    continue
                if associated is None:
                    raise ValueError(f"{module}: bound FAR fixup has no LEDATA")
                data_index, segment, start, position = associated
                kind = (location >> 10) & 15
                key, binding = active[target]
                frame = (fixdata >> 4) & 7
                frame_ok = frame == 5 or (frame == 0 and kind == 1
                                         and binding.get("allow_cs_code_frame", False))
                if (segment != code_segment or not location & 0x4000
                        or kind not in (1, 2, 3) or fixdata & 0x88
                        or not frame_ok):
                    raise ValueError(f"{module}: unsupported bound FAR location/frame/segment")
                local = location & 0x3FF
                offset = start + local
                width = 4 if kind == 3 else 2
                data = output[data_index]
                if (offset + width > module_size
                        or position + local + width > len(data) - 1):
                    raise ValueError(f"{module}: bound FAR fixup crosses retained LEDATA")
                if any(offset < end and begin < offset + width for begin, end in intervals):
                    raise ValueError(f"{module}: overlapping bound FAR fixups")
                intervals.append((offset, offset + width))
                if frame == 0:
                    frame_index, _ = read_index(payload, first + 3)
                    displacement = (0 if fixdata & 4 else
                                    int.from_bytes(payload[last - 2:last], "little"))
                    source = object_records[data_index]
                    if (frame_index != code_segment or local < 3 or displacement != 0
                            or bytes(source[position + local:position + local + 2]) != b"\0\0"
                            or (bytes(source[position + local - 3:position + local]) not in
                                (b"\x2e\x8e\x1e", b"\x2e\x8e\x06", b"\x2e\x8c\x0e"))):
                        # mov ds/es,cs:[disp16]: the overlay and EMS code also loads ES;
                        # RG2BTAIL stores CS itself (mov cs:[disp16],cs)
                        raise ValueError(f"{module}: CS CODE frame requires own segment, exact opcode and zero addends")
                negative = binding["offset_delta"] < 0
                if negative:
                    # This is a component addend, not a signed far-pointer
                    # alias or a carry into the paragraph. Admit only the
                    # demonstrated complete, initially zero POINTER32 form.
                    target_displacement = (0 if fixdata & 4 else
                                           int.from_bytes(payload[last - 2:last], "little"))
                    source = object_records[data_index]
                    if (kind != 3 or target_displacement != 0
                            or bytes(source[position + local:position + local + 4]) != b"\0" * 4):
                        raise ValueError(f"{module}: negative FAR offset requires zero-addend POINTER32")
                encoded_offset = binding["offset_delta"] & 0xFFFF if negative else binding["offset_delta"]
                components = [(0, encoded_offset)] if kind == 1 else (
                    [(0, binding["paragraph_delta"])] if kind == 2 else
                    [(0, encoded_offset), (2, binding["paragraph_delta"])])
                changed = bytearray(data[3:-1])
                for delta_position, adjustment in components:
                    p = position - 3 + local + delta_position
                    value = int.from_bytes(changed[p:p + 2], "little") + adjustment
                    if value > 0xFFFF:
                        raise ValueError(f"{module}: FAR native addend adjustment overflows")
                    changed[p:p + 2] = value.to_bytes(2, "little")
                output[data_index] = rebuild(0xA0, changed)
                positions.add(offset)
                consumed.add(target)
    if set(active) != consumed:
        raise ValueError(f"{module}: bound FAR external has no supported CODE reference")
    return output, {key: binding["native"] for key, binding in active.values()}, positions


def _file_version(path):
    stat = path.stat()
    return str(path), stat.st_mtime_ns, stat.st_size


@lru_cache(maxsize=4)
def _original_overlay_exports(version):
    from source_spans import _mz
    image = Path(version[0]).read_bytes()
    header, end, entries = _mz(image)
    overlays = []
    for paragraph, _, flags, _ in entries:
        if flags != 3:
            continue
        stub = header + paragraph * 16
        if stub + 32 > end or image[stub:stub + 2] != b'\xcd?':
            raise ValueError('Invalid original overlay stub header')
        delta, size, fieldbytes, count = struct.unpack_from('<I3H', image, stub + 4)
        body = end + 16 + delta
        if (fieldbytes % 2 or body + size + fieldbytes > len(image)
                or stub + 32 + 5 * count > end):
            raise ValueError('Invalid original overlay export bounds')
        exports = []
        for index in range(count):
            at = stub + 32 + 5 * index
            if image[at:at + 2] != b'\xcd?':
                raise ValueError('Invalid original overlay export opcode')
            offset = int.from_bytes(image[at + 2:at + 4], 'little')
            if offset >= size:
                raise ValueError('Original overlay export lies outside CODE')
            exports.append(offset)
        overlays.append((paragraph, image[body:body + size], tuple(exports)))
    if len({paragraph for paragraph, _, _ in overlays}) != len(overlays):
        raise ValueError('Ambiguous original overlay paragraphs')
    return tuple(overlays)


@lru_cache(maxsize=4)
def _canonical_overlay_bindings(original_version, layout_version, order_version, native_versions):
    """Prove native PUBLIC identities by FBOV order and body, never spelling."""
    from fixups import fixups
    import omf
    overlays = _original_overlay_exports(original_version)
    groups = [row['object'] for row in rows(Path(layout_version[0])) if row['overlay'] == '1']
    if len(groups) != len(overlays) or len(set(groups)) != len(groups):
        raise ValueError('Native overlay order disagrees with original segment table')
    order = defaultdict(list)
    for row in rows(Path(order_version[0])):
        order[row['object']].append((int(row['index']), row['symbol']))
    bindings = {}
    for group, (paragraph, code, exports), version in zip(groups, overlays, native_versions):
        raw = Path(version[0]).read_bytes()
        obj = fixups(raw)
        segments = [index for index, seg in enumerate(obj['segs'])
                    if seg and seg[0] == group + '_TEXT' and seg[1] == 'CODE']
        if len(segments) != 1:
            raise ValueError(f'{group}: ambiguous native own CODE segment')
        segment = segments[0]
        _, _, data, masks, _ = omf.module_masked(raw)
        if (obj['segs'][segment][2] != len(code) or len(data[segment]) != len(code)
                or len(masks[segment]) != len(code)
                or any(a != b and not mask for a, b, mask in zip(code, data[segment], masks[segment]))):
            raise ValueError(f'{group}: native fixed CODE bytes disagree with original overlay')
        ordered = sorted(order[group])
        if [index for index, _ in ordered] != list(range(len(exports))):
            raise ValueError(f'{group}: native export order disagrees with original overlay')
        for (index, symbol), body in zip(ordered, exports):
            if tuple(obj['pubs'].get(symbol, ())) != (segment, body):
                raise ValueError(f'{group}: native export {symbol} disagrees with original body')
            bindings[('FAR', paragraph, 32 + 5 * index)] = symbol
    return bindings


def canonical_overlay_targets(addresses):
    candidates = {name: value for name, value in addresses.items() if value[0] == 'FAR'}
    if not candidates:
        return {}
    original_version = _file_version(ORIGINAL)
    overlays = _original_overlay_exports(original_version)
    export_addresses = {('FAR', paragraph, 32 + 5 * index)
                        for paragraph, _, exports in overlays for index in range(len(exports))}
    candidates = {name: value for name, value in candidates.items() if value in export_addresses}
    if not candidates:
        return {}
    groups = [row['object'] for row in rows(ROOT / 'group-layout.csv') if row['overlay'] == '1']
    if any(not re.fullmatch(r'[A-Za-z0-9_]+', group) for group in groups):
        raise ValueError('Unsafe native overlay group name')
    bindings = _canonical_overlay_bindings(
        original_version, _file_version(ROOT / 'group-layout.csv'),
        _file_version(ROOT / 'overlay-order.csv'),
        tuple(_file_version(ROOT / 'groupobj' / (group + '.OBJ')) for group in groups))
    return {name: bindings[value] for name, value in candidates.items()}


