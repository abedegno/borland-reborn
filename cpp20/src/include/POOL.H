/* POOL.H: field access in BCC's far record pools.  Each pool is one segment, held
   in the variable named on each line; a record is an offset in it, and NAME(r, o)
   is the field at offset o of record r, of the type the suffix gives (W unsigned
   int, B unsigned char, L long, I int, SC signed char, UL unsigned long).  The
   prefixes: EXPR expression nodes, TYPE types, TSEG SYMBOL_POOL_SEG records, LINK
   expression links, MEMBER members, PARAM parameters, SYM2 the second symbol
   segment, STMT statement records, NAME the name pool; Pnnnn pools are named by their segment
   variable's DS offset until their role is known.  FAR_x(s, r, o) is the field at
   offset o of record r in segment s, AT_x(s, o) the item at s:o, and ES_x(r, o)
   the field of record r in the segment held in ES.
   Generated during the readability pass. */
