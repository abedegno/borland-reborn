"""Write docs/SOURCE-MAP.md: every source in image order with its role and functions.

    python3 tools/sourcemap.py

The role is the first sentence of the source's "Role:" line (or of its first header comment
after the build lines and provenance note); the functions are its target table's rows."""
import os, re
R = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
rows = [l.rstrip('\n').split('\t') for l in open(os.path.join(R, 'map', 'modules.tsv')) if not l.startswith('#')]
def role(path):
    s = open(os.path.join(R, path), encoding='latin1').read().replace('\r', '')
    if path.upper().endswith('.ASM'):
        blocks, cur = [], []
        for l in s.split('\n')[:80]:
            if l.startswith(';'):
                cur.append(l.lstrip(';').strip())
            else:
                if cur: blocks.append(' '.join(cur)); cur = []
                if l.strip(): break
        if cur: blocks.append(' '.join(cur))
        text = ' '.join(blocks)
        text = re.sub(r'/\*.*?\*/', ' ', text)
    else:
        blocks = re.findall(r'/\*(.*?)\*/', s[:8000], re.S)
        blocks = [b for b in blocks if not re.match(r'\s*(target|opts|compiler|link|cflags):', b)]
        text = ' '.join(blocks)
    text = re.sub(r'\s+', ' ', text)
    m = re.search(r'Role:\s*(.*?)(?:\.\s|$)', text)
    if m: return m.group(1).strip().rstrip('.') + '.'
    text = re.sub(r'^\s*CPP\.EXE module .*?\.\s+(?=[A-Z])', '', text, count=1)
    text = re.sub(r'^.*?its code is the same in both programs\.\s*', '', text, count=1)
    m = re.match(r'(.*?\.)(\s|$)', text.strip())
    return (m.group(1) if m else text[:160]).strip()
def compiler(path):
    s = open(os.path.join(R, path), encoding='latin1').read(400)
    if path.upper().endswith('.ASM'): return 'TASM'
    return 'Turbo C 2.01' if 'compiler: TC201' in s else 'BC 2.0'
out = ['# Source map', '',
       'Every source of cpp20 in CPP.EXE image order: its file, what it rebuilds (target, image range),',
       'the compiler, its role (from its header comment) and its functions (from targets/<TARGET>.tsv).',
       'Generated by tools/sourcemap.py.', '',
       '| Source | Target | Image | Compiler | Role | Functions |', '|---|---|---|---|---|---|']
for r in rows:
    name, frame, a, b, size, org, nf, matched, src = r
    funcs = [l.split('\t')[0] for l in open(os.path.join(R, 'targets', name + '.tsv')).read().split('\n')[1:] if l.strip()]
    out.append(f'| [{src[4:]}](../{src}) | {name} | {a}..{b} | {compiler(src)} | {role(src).replace("|", "/")} | {", ".join(funcs)} |')
out += ['', 'Data: `src/data/*.ASM` (generated by `scripts/prepare.py`, not committed) hold DGROUP and the far',
        'data; see FINDINGS.md, "Data owners".']
open(os.path.join(R, 'docs', 'SOURCE-MAP.md'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'sources')
